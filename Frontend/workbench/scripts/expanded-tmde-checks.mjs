import { mkdirSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { setTimeout } from 'node:timers/promises';

export async function checkExpandedTmde({ frame, page, saved }) {
  const waitForSave = async predicate => {
    const deadline = Date.now() + 15000;
    while (!predicate(saved()) && Date.now() < deadline) await setTimeout(100);
    if (!predicate(saved())) writeFileSync('tmp/expanded-tasking/failed-save.json', JSON.stringify(saved(), null, 2));
    assert.ok(predicate(saved()), 'edited uncertainty is persisted');
  };
  mkdirSync('tmp/expanded-tasking',{recursive:true});
  await page.setViewportSize({width:1600,height:1200});
  if (await page.locator('#app').count()) await page.locator('#app').evaluate(el=>el.style.height='1150px');
  const click = async locator => {
    const initial=await locator.boundingBox();
    if (initial && (initial.y < 150 || initial.y+initial.height > 1050 || initial.x < 0 || initial.x + initial.width > 1580)) await locator.evaluate(el => el.scrollIntoView({block:'center',inline:'nearest',behavior:'instant'}));
    const b=await locator.boundingBox();
    assert.ok(b && b.width && b.height);
    await page.mouse.click(b.x+b.width/2,b.y+b.height/2);
  };
  console.log('expanded: open cell');
  const table = frame.locator('.instrument-equipment-table').nth(1);
  const cell = table.locator('tr.instrument-function-row').first().locator('.cell-tolerance');
  const hoverStyle = el => ({ color: getComputedStyle(el).color, background: getComputedStyle(el).backgroundColor, border: getComputedStyle(el).borderTopColor });
  await cell.locator('.inline-tolerance-summary').hover();
  await setTimeout(180);
  const tableHover = await cell.locator('.inline-tolerance-summary').evaluate(hoverStyle);
  await click(cell.locator('.inline-tolerance-summary'));
  const editor = cell.locator('.inline-tolerance-editor');
  const addControl = editor.getByRole('button', { name: 'Add a secondary uncertainty', exact: true });
  await addControl.hover();
  await setTimeout(180);
  assert.deepEqual(await addControl.evaluate(hoverStyle), tableHover, 'plus hover matches the measurement-area table styling');
  const mode = await editor.getByRole('group', { name: 'Tolerance symmetry' }).boundingBox();
  assert.equal(await editor.getByRole('button', { name: 'Uncertainty settings', exact: true }).count(), 0);
  const settings = await editor.getByRole('button', { name: 'Add a secondary uncertainty', exact: true }).boundingBox();
  assert.ok(Math.abs(mode.y - settings.y) < 5, 'add control shares the tolerance toolbar');
  const symmetric = await editor.evaluate(el => el.getBoundingClientRect().width);
  await click(editor.getByTitle('Asymmetric tolerance', { exact: true }));
  const asymmetric = await editor.evaluate(el => el.getBoundingClientRect().width);
  assert.ok(asymmetric > symmetric + 20, `expanded width follows visible fields: ${symmetric}, ${asymmetric}`);
  const symButton = await editor.getByTitle('Symmetric tolerance', { exact: true }).boundingBox();
  await page.mouse.click(symButton.x + symButton.width / 2, symButton.y + symButton.height / 2);
  console.log('expanded: symmetric restored');
  await click(editor.getByRole('button',{name:'Bias',exact:true}));
  assert.equal(await editor.locator('.instrument-bias-label').textContent(),'Bias:');
  await page.screenshot({path:'tmp/expanded-tasking/parametric-light.png'});
  console.log('expanded: add secondary');
  await click(editor.getByRole('button', { name: 'Add a secondary uncertainty' }));
  assert.equal(await table.getByRole('textbox', { name: 'Uncertainty name' }).count(), 0, 'choose type before naming');
  await click(editor.getByRole('button', { name: 'Manual', exact: true }));
  const sourceRow = table.locator('tr[data-uncertainty-source-id]').first();
  const sourceName = sourceRow.getByRole('textbox', { name: 'Uncertainty name' });
  await sourceName.fill('Thermal Expansion');
  await sourceName.press('Tab');
  const sourceEditor = sourceRow.locator('.inline-tolerance-editor');
  await sourceEditor.waitFor();
  assert.equal(await sourceEditor.getByRole('button', { name: 'Bias', exact: true }).count(), 0);
  assert.ok(await sourceRow.getByText('(Range N/A)', { exact: true }).isVisible());
  assert.equal(await sourceRow.locator('.cell-resolution').textContent(), 'N/A');
  const floor = sourceEditor.locator('.inline-tolerance-term-group').nth(2).locator('input').first();
  await floor.fill('0.3');
  await click(sourceEditor.getByRole('button', { name: 'Tolerance unit base unit', exact: true }));
  await frame.getByRole('option', { name: /^V(?:\s|$)/ }).click();
  const instrumentInputFont = await floor.evaluate(node => getComputedStyle(node).fontSize);
  await floor.press('Enter');
  await sourceRow.locator('.cell-distribution .inline-distribution-summary').click();
  await frame.getByRole('option', { name: /^Rectangular k/ }).click();
  await waitForSave(data => data.tmdes[0].instrument?.tmdeSecondaryUncertainties?.[0]?.tolerance?.floor?.high === '0.3');
  await page.screenshot({ path: 'tmp/expanded-tasking/secondary-light.png' });
  console.log('expanded: table and equation rows through add control');
  for (const kind of ['Table', 'Equation']) {
    await click(sourceRow.locator('.cell-tolerance .inline-tolerance-summary'));
    const sourceToolbar = sourceRow.locator('.inline-tolerance-editor');
    await click(sourceToolbar.getByRole('button', { name: 'Add a secondary uncertainty' }));
    await click(sourceToolbar.getByRole('button', { name: kind, exact: true }));
    const row = table.locator('tr[data-uncertainty-source-id]').last();
    assert.equal(await row.locator('.cell-tolerance .is-empty').textContent(), 'Not Set', 'new dynamic uncertainty uses the common placeholder');
    const name = row.getByRole('textbox', { name: 'Uncertainty name' });
    await name.fill(kind + ' test');
    await name.press('Tab');
    const dynamic = row.locator('.inline-tolerance-editor');
    const firstValue = dynamic.getByRole('textbox', { name: kind === 'Table' ? 'Measurement point row 1' : 'Uncertainty equation', exact: true });
    assert.ok(await firstValue.evaluate(el => el === document.activeElement), 'Tab from name focuses the uncertainty value');
    assert.equal(await dynamic.locator('.dynamic-editor-footer').count(), 0, 'instrument editor omits the informational footer');

    const plusBounds = await dynamic.getByRole('button', { name: 'Add a secondary uncertainty' }).boundingBox();
    const editorBounds = await dynamic.boundingBox();
    assert.ok(Math.abs(editorBounds.x + editorBounds.width - plusBounds.x - plusBounds.width) < 12, 'add stays at the editor right edge');
    assert.ok(plusBounds.y - editorBounds.y < 12, 'add stays at the editor top');

    if (kind === 'Table') {
      await dynamic.getByRole('textbox', { name: 'Measurement point row 1', exact: true }).fill('5');
      await dynamic.getByRole('textbox', { name: 'Uncertainty row 1', exact: true }).fill('0.2');
    } else {
      await dynamic.getByRole('textbox', { name: 'Uncertainty equation', exact: true }).fill('x / 25');
    }
    assert.equal(await dynamic.getByRole('button', { name: /distribution|interpretation/i }).count(), 0, 'distribution is edited in its table column only');
    assert.equal(await dynamic.locator('.dynamic-budget-editor').count(), 1, 'instrument uses the shared budget editor');
    assert.equal(await dynamic.locator('input').first().evaluate(node => getComputedStyle(node).fontSize), instrumentInputFont, 'dynamic input font matches other instrument inputs');
    assert.ok(await dynamic.locator('.dynamic-input-table th').evaluateAll(nodes => nodes.every(node => getComputedStyle(node).whiteSpace === 'nowrap')), 'dynamic headers remain on one line');
    assert.ok(await dynamic.locator('.dynamic-input-table').evaluate(table => {
      const layers = [table.tHead, ...table.tHead.rows, ...table.tHead.querySelectorAll('th')];
      return layers.every(node => {
        const style = getComputedStyle(node);
        return style.backgroundColor === 'rgba(0, 0, 0, 0)' && style.backgroundImage === 'none';
      }) && getComputedStyle(table.tHead).position === 'static'
        && getComputedStyle(table.tHead, '::before').display === 'none';
    }), 'nested headers reveal the measurement-area surface without an opaque or sticky header layer');
    await page.screenshot({ path: 'tmp/expanded-tasking/shared-' + kind.toLowerCase() + '-editor.png' });
    await row.locator('.cell-distribution .inline-distribution-summary').click();
    await frame.getByRole('option', { name: /^Rectangular k/ }).click();
    await waitForSave(data => data.tmdes[0].instrument.tmdeSecondaryUncertainties.at(-1)?.dynamicDefinition?.distribution === '1.732');
    await page.keyboard.press('Escape');
    const remove = row.getByRole('button', { name: 'Remove ' + kind + ' test', exact: true });
    await row.locator('.range-row-cell').hover();
    await table.locator('tr[data-range-id]:not([data-uncertainty-source-id]) td[data-range-cell]').first().click({ position: { x: 2, y: 2 } });
    const rangeRemove = table.locator('tr:not([data-uncertainty-source-id]) .range-row-delete').first();
    const expectedBox = await rangeRemove.boundingBox();
    assert.equal(await remove.count(), 0, 'unselected source does not expose delete');
    await table.locator("tr[data-range-id]:not([data-uncertainty-source-id]) .range-row-cell").first().hover();
    await rangeRemove.hover();
    await setTimeout(150);
    const rangeStyle = await rangeRemove.evaluate(el => ({ color: getComputedStyle(el).color, background: getComputedStyle(el).backgroundColor }));
    await row.locator('.instrument-source-range-note').click();
    const actualBox = await remove.boundingBox();
    assert.ok(Math.abs(actualBox.x - expectedBox.x) < 1, 'source delete aligns with range delete');
    assert.equal(actualBox.width, expectedBox.width);
    assert.equal(actualBox.height, expectedBox.height);
    await frame.locator('.analysis-tabs').hover();
    await setTimeout(150);
    assert.equal(await remove.evaluate(el => getComputedStyle(el).opacity), '0', 'selected source hides delete away from hover');
    await row.locator(".range-row-cell").hover();
    await remove.hover();
    await setTimeout(150);
    assert.deepEqual(await remove.evaluate(el => ({ color: getComputedStyle(el).color, background: getComputedStyle(el).backgroundColor })), rangeStyle, 'source delete uses the same red hover as range delete');
    await click(remove);
    await waitForSave(data => data.tmdes[0].instrument.tmdeSecondaryUncertainties.length === 1);
    if (kind === 'Table') await click(frame.getByRole('button', { name: 'Switch to dark mode', exact: true }));
  }
  console.log('expanded: add to budget');
  const previousIds = new Set(saved().testPoints[0].components.map(c => c.id));
  const expand = frame.getByRole('button', { name: 'Expand measurement area', exact: true });
  if (await expand.count()) await click(expand.first());
  console.log('expanded: measurement area expanded');
  await frame.locator('[data-point-id="point"] [data-sidebar-column="pfa"]').click({ position: { x: 2, y: 2 } });
  console.log('expanded: point selected');
  const inputBudgetAdd = frame.locator('.budget-stack-section:not(.final)').getByRole('button', { name: 'Add component to budget', exact: true }).first();
  await inputBudgetAdd.waitFor({ state: 'visible' });
  await inputBudgetAdd.click();
  console.log('expanded: budget picker opened');
  const menu = frame.getByRole('dialog', { name: 'Add component to budget', exact: true });
  await menu.waitFor({ state: 'visible' });
  await click(menu.locator('.budget-tmde-picker-range, .budget-tmde-picker-single').first());
  await waitForSave(data => data.testPoints[0].components.filter(c => c.tmdeBudgetSourceId === 'tmde' && !previousIds.has(c.id)).length === 1);
  const sourceChoice = menu.locator('.budget-tmde-picker-source').filter({ hasText: 'Thermal Expansion' });
  assert.equal(await sourceChoice.count(), 1, 'instrument source is listed once');
  assert.ok((await sourceChoice.textContent()).includes('Thermal Expansion (Manual) | ± 0.3 V | Rectangular'));
  assert.equal(await sourceChoice.locator('.budget-tmde-picker-range-mark').count(), 1);
  await page.screenshot({ path: 'tmp/expanded-tasking/grouped-budget-picker.png' });
  await click(sourceChoice);
  console.log('expanded: source added separately');
  await frame.locator('.analysis-tabs').click({ position: { x: 5, y: 5 } });
  const newTmdeRows = data => data.testPoints[0].components.filter(c => c.tmdeBudgetSourceId === 'tmde' && !previousIds.has(c.id));
  await waitForSave(data => newTmdeRows(data).length === 2);
  const added = newTmdeRows(saved());
  assert.equal(added.length, 2, 'primary and secondary both added to the input budget');
  assert.ok(added.some(c => c.tmdeUncertaintySourceName === 'Thermal Expansion'));
  // Independent source summaries resolve against the selected point.
  const detailSource = frame.locator('tr[data-uncertainty-source-id]').first();
  assert.ok((await detailSource.locator('.cell-tolerance').textContent()).includes('0.3'), 'point view displays the actual manual spec');
  const point = frame.locator('[data-point-id="point"]');
  const unit = point.getByRole('button', { name: 'Measurement point unit base unit', exact: true });
  const prefix = point.getByRole('button', { name: 'Measurement point unit prefix', exact: true });
  await unit.click(); await frame.getByRole('option', {name:/^Pa\s/}).click();
  await prefix.click(); await frame.getByRole('option', {name:/^Kilo\s/}).click();
  await waitForSave(data => data.testPoints[0].testPointInfo.parameter.unit === 'kPa');
  assert.ok(await frame.getByRole('button', { name: 'Add component to budget', exact: true }).first().isVisible(), 'incompatible units retain the budget');
  await prefix.click(); await frame.getByRole('option', {name:/^Base\s/}).click();
  await unit.click(); await frame.getByRole('option', {name:/^V\s+Voltage$/}).click();
  const divider = frame.getByRole('separator', { name: 'Resize measurement point list' });
  await divider.dblclick();
  await frame.locator('.workspace-pane-autofit').waitFor();
  await divider.dblclick();
  await frame.locator('.workspace-pane-tables:not(.workspace-pane-autofit)').waitFor();
  await divider.dblclick();
  await frame.locator('.workspace-pane-points:not(.workspace-pane-autofit)').waitFor();
  assert.ok(await divider.evaluate(node => getComputedStyle(node, '::after').opacity === '1'), 'full-width divider remains highlighted');
  await divider.dblclick();
  await frame.locator('.workspace-pane-autofit').waitFor();
  const geometry = await point.locator('[data-sidebar-column="value"]').evaluate(cell => {
    const bounds = cell.getBoundingClientRect();
    return [...cell.querySelectorAll('.inline-unit-select button')].every(select => { const r = select.getBoundingClientRect(); return r.left >= bounds.left && r.right <= bounds.right + 1; });
  });
  assert.ok(geometry, 'auto-fit contains both unit and prefix controls');
  await divider.focus(); await divider.press('Escape');
  const hint = frame.locator('.measurement-point-empty-hint').first();
  await setTimeout(300);
  await page.screenshot({ path: 'tmp/expanded-tasking/arrow-check.png' });
  if (await hint.count()) { assert.ok(await hint.evaluate(node => {
    const arrow = node.querySelector('span').getBoundingClientRect();
    const add = node.closest('.measurement-group-container').querySelector('.function-point-add-button').getBoundingClientRect();
    return Math.abs(arrow.x + arrow.width / 2 - add.x - add.width / 2) < 2;
  }), 'empty point hint arrow aligns with add button'); }
  await page.screenshot({ path: 'tmp/expanded-tasking/final-point-dark.png' });
  console.log('expanded: uncertainty row selection and deletion');
  const originalRanges = saved().tmdes[0].ranges.map(range => range.id);
  await detailSource.locator('.instrument-source-range-note').click();
  assert.equal(await detailSource.getAttribute('data-range-selected'), 'true');
  await page.keyboard.press('Delete');
  await waitForSave(data => !data.tmdes[0].instrument.tmdeSecondaryUncertainties.length);
  assert.deepEqual(saved().tmdes[0].ranges.map(range => range.id), originalRanges, 'deleting a source preserves actual ranges');

  await frame.locator('[data-tour="tab-overview"]').click();
  for (const name of ['Delete test A', 'Delete test B']) {
    await click(cell.locator('.inline-tolerance-summary').first());
    await click(editor.getByRole('button', { name: 'Add a secondary uncertainty' }));
    await click(editor.getByRole('button', { name: 'Manual', exact: true }));
    const row = table.locator('tr[data-uncertainty-source-id]').last();
    const input = row.getByRole('textbox', { name: 'Uncertainty name' });
    await input.fill(name);
    await input.press('Tab');
    assert.equal(await row.getByRole('button', { name: 'Uncertainty settings', exact: true }).count(), 0, 'source rows have no redundant gear');
    await page.keyboard.press('Escape');
  }
  await waitForSave(data => data.tmdes[0].instrument.tmdeSecondaryUncertainties.length === 2);
  const rows = table.locator('tr[data-uncertainty-source-id]');
  await rows.first().locator('.instrument-source-range-note').click();
  await rows.last().locator('.instrument-source-range-note').click({ modifiers: ['Shift'] });
  assert.equal(await table.locator('tr[data-uncertainty-source-id][data-range-selected="true"]').count(), 2);
  await rows.last().locator('.instrument-source-range-note').click({ button: 'right' });
  await frame.getByText('Delete Selected Rows', { exact: true }).click();
  await waitForSave(data => !data.tmdes[0].instrument.tmdeSecondaryUncertainties.length);
  assert.deepEqual(saved().tmdes[0].ranges.map(range => range.id), originalRanges);
  console.log('PASS expanded TMDE primary/secondary authoring, distribution, compact widths, type selection, and budget addition');
}
